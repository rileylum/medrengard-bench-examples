#!/usr/bin/env python3
"""Regenerate textdrop_bundle.py from ./static, ./docs and ./templates."""
import base64
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def collect(sub):
    base = os.path.join(ROOT, sub)
    out = {}
    for dirpath, _, files in os.walk(base):
        for f in sorted(files):
            full = os.path.join(dirpath, f)
            rel = os.path.relpath(full, base).replace(os.sep, "/")
            with open(full, "rb") as fh:
                out[rel] = base64.b64encode(fh.read()).decode("ascii")
    return dict(sorted(out.items()))


def main():
    lines = ['"""Bundled TextDrop resources (generated by tools/build_bundle.py; do not edit)."""',
             "import base64 as _b64", ""]
    for name in ("static", "docs", "templates"):
        lines.append(f"_{name.upper()} = {{")
        for k, v in collect(name).items():
            lines.append(f"    {k!r}: {v!r},")
        lines.append("}")
        lines.append(f"{name.upper()} = {{k: _b64.b64decode(v) for k, v in _{name.upper()}.items()}}")
        lines.append("")
    with open(os.path.join(ROOT, "textdrop_bundle.py"), "w") as fh:
        fh.write("\n".join(lines))


if __name__ == "__main__":
    main()
